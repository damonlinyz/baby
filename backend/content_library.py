def catalogue():
    rows=[]
    for group,entries in GROUPS.items():
        for index,(title,first) in enumerate(entries,1):
            rows.append({'id':str(list(GROUPS).index(group)+1)+'-'+str(index),'group':group,'title':title,
                         'note':first+'。由家人按实际需要选择，不自动推算医疗安排。',
                         'steps':[first,'与相关家人确认负责人、需要的帮助和合适时间','完成后核对实际结果；安排不合适时及时修改或跳过'],
                         'source':'产品编辑 · 一般家庭生活可选模板','content_version':1,'clinical':False})
    return {'templates':rows,'notice':'84 项可选生活模板，不自动加入家庭；就诊、手续与用品要求以对应机构或原说明为准。未作专业医疗审校。'}


def create(c,fid,user,data):
    import domain as d
    d.member(c,fid,user,('dad',))
    template=next((t for t in catalogue()['templates'] if t['id']==data.get('template_id')),None)
    if not template:raise d.Problem(404,'模板不存在')
    if data.get('confirmed') is not True:raise d.Problem(400,'请确认按家庭实际需要选用此模板')
    payload={k:data[k] for k in ('assignee','due_date') if k in data}
    payload.update(title=template['title'],note=template['note'],steps=template['steps'],knowledge_ids=[])
    result=d.mutate(c,user,fid,'task.create',payload)
    task=d.require_active(c,fid,'task',result['id']);task.update(pregnancy_id=None,stage=None,type={'沟通与陪伴':'陪伴与沟通','日常家务':'家庭协作','证件与资料':'资料准备'}.get(template['group'],'家庭协作'),template_source=template['source'],template_version=1,library_template_id=template['id'])
    d.put(c,'task',task,fid)
    return result
